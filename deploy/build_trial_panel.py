"""Bundle the standalone trace view for manage's isolated AstrBot Page asset root."""

from pathlib import Path

PAGES = Path(__file__).resolve().parents[1] / "pages"
OUTPUT = PAGES / "manage" / "trials.js"


def build():
    source = PAGES / "测试群调用"
    html = (source / "index.html").read_text(encoding="utf-8")
    body = html[html.index("<main>") + len("<main>") : html.index("</main>")].strip()
    css = (source / "style.css").read_text(encoding="utf-8")
    css = css.replace(":root {", ":host {").replace("body {", ":host {")
    css = css.replace('[data-theme="dark"] {', ':host([data-theme="dark"]) {')
    markup = f"<style>\n{css}</style>\n{body}"
    markup = markup.replace("\\", "\\\\").replace("`", "\\`").replace("${", "\\${")
    js = (source / "app.js").read_text(encoding="utf-8")
    # Only trusted, checked-in markup goes into this template. All chat and
    # provider data still flow through the original renderer's textContent.
    return (
        "// Generated by deploy/build_trial_panel.py from pages/测试群调用.\n"
        'const host = document.getElementById("panel-trials");\n'
        'const shadow = host.attachShadow({mode: "open"});\n'
        f"shadow.innerHTML = `{markup}`;\n"
        'const syncTheme = () => { host.dataset.theme = document.documentElement.dataset.theme || "light"; };\n'
        'new MutationObserver(syncTheme).observe(document.documentElement, {attributes: true, attributeFilter: ["data-theme"]});\n'
        "syncTheme();\n\n" + js
    )


if __name__ == "__main__":
    OUTPUT.write_text(build(), encoding="utf-8")
